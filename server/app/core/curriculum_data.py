def validate() -> None:
    """Assert authoring invariants. Called from a unit test, not at import time."""
    from app.core.store import SUBTOPIC_DEFINITIONS

    expected_ids = set(range(1, len(SUBTOPIC_DEFINITIONS) + 1))
    assert set(SUBTOPIC_NOTES) == expected_ids, f"SUBTOPIC_NOTES missing ids: {expected_ids - set(SUBTOPIC_NOTES)}"
    assert set(SUBTOPIC_QUESTIONS) == expected_ids, f"SUBTOPIC_QUESTIONS missing ids: {expected_ids - set(SUBTOPIC_QUESTIONS)}"

    for sid in expected_ids:
        levels = SUBTOPIC_NOTES[sid]
        assert set(levels) == {"beginner", "intermediate", "advanced"}, f"subtopic {sid}: bad level keys {set(levels)}"
        for level, body in levels.items():
            assert body.strip(), f"subtopic {sid}/{level}: empty body"

        stages = SUBTOPIC_QUESTIONS[sid]
        assert len(stages.get("diagnostic", [])) == 4, f"subtopic {sid}: diagnostic must have 4 questions"
        assert len(stages.get("first", [])) == 15, f"subtopic {sid}: first must have 15 questions"
        for stage, seeds in stages.items():
            for i, seed in enumerate(seeds):
                assert seed["correct_answer"] in ("A", "B", "C", "D"), f"subtopic {sid}/{stage}[{i}]: bad correct_answer"
                assert seed["concept"].strip(), f"subtopic {sid}/{stage}[{i}]: empty concept"
        diff_seq = [q["difficulty"] for q in stages["first"]]
        assert diff_seq == ["easy"] * 5 + ["medium"] * 5 + ["hard"] * 5, f"subtopic {sid}: first-stage difficulty order must be 5 easy/5 medium/5 hard"
